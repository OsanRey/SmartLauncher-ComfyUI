from __future__ import annotations

from pathlib import Path

from smart_launcher.domain.commands import CommandSpec
from smart_launcher.infrastructure.command_runner import CommandRunner


PROBE = r'''
def _probe():
    import base64
    import csv
    import hashlib
    import importlib.metadata as metadata
    import json
    import sys
    from pathlib import Path

    errors = []
    warnings = []
    checked = 0
    unhashed = 0
    try:
        if sys.argv[1] == "--all":
            distributions = list(metadata.distributions())
        else:
            report = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
            if report.get("version") != "1" or not isinstance(report.get("install"), list):
                raise ValueError("Invalid pip installation report")
            distributions = [metadata.distribution(item["metadata"]["name"])
                             for item in report["install"]]
        for dist in distributions:
            name = dist.metadata.get("Name") or str(dist._path)
            record = dist.read_text("RECORD")
            if record is None:
                warnings.append(f"{name}: RECORD absent; file integrity not verified")
                continue
            if not record.strip() or "\0" in record:
                errors.append(f"{name}: invalid RECORD")
                continue
            rows = list(csv.reader(record.splitlines()))
            package_unhashed = 0
            for row in rows:
                if len(row) != 3:
                    errors.append(f"{name}: invalid RECORD")
                    continue
                filename, digest, size = row
                normalized = filename.replace("\\", "/")
                if not filename or "\0" in filename:
                    errors.append(f"{name}: invalid file path in RECORD")
                    continue
                # Generated bytecode may legitimately be removed or regenerated.
                if normalized.endswith(".pyc") and not digest and not size:
                    continue
                path = Path(dist.locate_file(normalized))
                try:
                    hasher = None
                    if digest:
                        algorithm, expected = digest.split("=", 1)
                        hasher = hashlib.new(algorithm)
                    elif not normalized.endswith(("/RECORD", "/RECORD.jws", "/RECORD.p7s")):
                        package_unhashed += 1
                        unhashed += 1
                    actual_size = 0
                    null_source = False
                    with path.open("rb") as handle:
                        while block := handle.read(1024 * 1024):
                            if hasher is not None:
                                hasher.update(block)
                            if normalized.endswith(".py") and b"\0" in block:
                                null_source = True
                            actual_size += len(block)
                    if hasher is not None and base64.urlsafe_b64encode(hasher.digest()).decode().rstrip("=") != expected:
                        errors.append(f"{name}: checksum mismatch: {filename}")
                    if size and actual_size != int(size):
                        errors.append(f"{name}: size mismatch: {filename}")
                    if null_source:
                        errors.append(f"{name}: null bytes in Python source: {filename}")
                    checked += 1
                except (OSError, ValueError) as exc:
                    errors.append(f"{name}: {filename}: {exc}")
            if package_unhashed:
                warnings.append(f"{name}: {package_unhashed} files without hashes; limited verification")
    except Exception as exc:
        errors.append(str(exc))
    print(json.dumps({"checked": checked, "unhashed": unhashed,
                      "warnings": warnings[:50], "errors": errors[:50]}, ensure_ascii=True))
    sys.exit(1 if errors else 0)


_probe()
'''


class PackageIntegrity:
    def __init__(self, runner: CommandRunner | None = None):
        self.runner = runner or CommandRunner()

    def verify(self, python: Path, report: Path | None = None, *, cancel_event=None, on_chunk=None):
        result = self.runner.run(
            CommandSpec(
                argv=(str(python), "-I", "-B", "-c", PROBE, str(report) if report else "--all"),
                source="package-integrity", timeout=3600,
                env={"PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8"},
            ), cancel_event=cancel_event, on_chunk=on_chunk,
        )
        return result
